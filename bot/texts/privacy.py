_DOMESTIC = frozenset({"беларусь", "республика беларусь", "рб", "belarus"})


class PrivacyFacts(Protocol):
    operator_name: str | None
    operator_address: str | None
    storage_country: str | None
    support_contact: str | None
    rules_url: str
    privacy_url: str
    rules_version: str
    privacy_version: str
    receipt_retention_days: int
    require_age_confirmation: bool
    channel_title: str | None


def _days(number: int) -> str:
    return f"{number} {plural_ru(number, 'день', 'дня', 'дней')}"


def _filled(value: str | None, fallback: str) -> str:
    text = (value or "").strip()
    return text or fallback


def _storage_sentence(country: str | None) -> str:
    cleaned = (country or "").strip()
    if cleaned.casefold() in _DOMESTIC:
        return "База заявок и файлы чеков хранятся в Беларуси."
    if cleaned:
        return (
            f"База заявок и файлы чеков хранятся в стране: {cleaned}. "
            "Если эта страна не входит в перечень стран с надлежащим уровнем защиты прав "
            "(приказ директора Национального центра защиты персональных данных "
            "от 15 ноября 2021 г. № 14), передача туда тоже основана на вашем согласии."
        )
    return (
        "Страна серверов, где лежат база и файлы чеков, не указана. "
        "Помимо Telegram возможна передача в страну, которую по этому тексту установить нельзя."
    )


def _telegram_risks() -> str:
    return (
        "Сообщения и файлы проходят через Telegram. Серверы Telegram находятся за пределами "
        "Беларуси, и точную страну оператор определить не может. Из-за этого возможны такие "
        "риски: в другой стране может не быть закона о персональных данных, к ним могут "
        "относить более узкий круг сведений, может не быть органа по защите этих прав, "
        "а перечень прав может быть меньше, чем в Беларуси. Без Telegram бот не работает, "
        "поэтому согласие на участие включает и эту передачу."
    )


def _contact_line(facts: PrivacyFacts) -> str:
    contact = _filled(facts.support_contact, "этому боту")
    return f"Вопросы по персональным данным: {contact}."


def _channel_phrase(facts: PrivacyFacts) -> str:
    title = (facts.channel_title or "").strip()
    if not title:
        return "в канале розыгрыша"
    return f"в канале «{title}»"


