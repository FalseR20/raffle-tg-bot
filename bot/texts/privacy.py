    "\n"
    "3. Цели обработки данных\n"
    "Персональные данные обрабатываются исключительно в целях:\n"
    "- Идентификации участника в розыгрыше;\n"
    "- Расчета и выдачи уникальных номеров участников;\n"
    "- Сверки факта совершения пожертвования с волонтерами "
    "и благотворительными организациями;\n"
    "- Определения и объявления победителей розыгрыша.\n"
    "\n"
