    limit = MESSAGE_LIMIT - 200
    for block in _policy_blocks(facts):
        candidate = block if not current else f"{current}\n\n{block}"
        if current and len(candidate) > limit:
            pages.append(current)
            current = block
        else:
            current = candidate
    if current:
        pages.append(current)
    return pages
