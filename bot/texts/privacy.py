    "Политика в отношении обработки персональных данных участников "
    "благотворительного розыгрыша в Telegram-канале «Тетрадь с полями»\n"
    "\n"
    "1. Общие положения\n"
    "Настоящая Политика определяет порядок обработки персональных данных "
    "участников благотворительного розыгрыша, проводимого в Telegram-канале "
    "«Тетрадь с полями» (далее — Организатор), в соответствии с Законом "
    "Республики Беларусь от 7 мая 2021 г. № 99-З «О защите персональных данных».\n"
    "\n"
    "2. Какие данные мы собираем\n"
    "Для участия в розыгрыше чат-бот собирает следующие данные:\n"
    "- Идентификатор пользователя Telegram (Telegram ID) и юзернейм (@username);\n"
    "- Имя, указанное пользователем в профиле;\n"
    "- Данные, содержащиеся на скриншотах чеков пожертвований "
    "(включая сумму перевода, дату, время и имя отправителя, "
