def withdrawal_done(*, failed: int, profile_cleared: bool = True) -> str:
    name = (
        "Ник и имя удалены из профиля. "
        if profile_cleared
        else "Ник сотрудника бота сохранён: он нужен для работы в панели. "
    )
    text = esc(
        "Согласие отозвано. " + name + "Незавершённые заявки отменены. "
        "Файлы чеков удаляются. Номера уже выданных билетов остаются без имени."
    )
    if failed:
        text += "\n\n" + esc(
            "Часть файлов удалить сразу не удалось. Откройте /privacy и отзовите согласие "
            "ещё раз или напишите в поддержку. На удаление есть 15 дней."
        )
    return text


def withdrawal_kept() -> str:
    return esc("Согласие остаётся в силе.")


