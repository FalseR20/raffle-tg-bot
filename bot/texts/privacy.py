"""Privacy notice and policy shown to participants.

The copy follows the Law of the Republic of Belarus of 7 May 2021 No. 99-Z
"On personal data protection" and the National Personal Data Protection Centre
clarifications of 24 April 2025 on operator policies. It is a product draft:
the operator's name, address and hosting country come from settings, and a
lawyer should review them before launch.

The pre-consent notice is separate from the full policy. Article 5 requires
the operator, purposes, data, term, authorised persons, actions and the
person's rights before consent, and the rights explanation must not be buried
in the rules or the policy.
"""

from __future__ import annotations

from typing import Protocol

from bot.texts.markdown import MESSAGE_LIMIT, escape_url
